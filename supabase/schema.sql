-- The table and bucket the app expects. Safe to run on a fresh project; on the
-- existing project everything here already exists.

create table if not exists public.reviews (
  id          bigint generated by default as identity primary key,
  restaurant_id text        not null,          -- a Spot id from lib/spots.ts
  rating      smallint    not null,
  comment     text        not null default '',
  user_name   text        not null default 'Anonymous',
  image_url   text,
  created_at  timestamptz not null default now()
);

create index if not exists reviews_restaurant_created_idx
  on public.reviews (restaurant_id, created_at desc);

insert into storage.buckets (id, name, public)
values ('review-images', 'review-images', true)
on conflict (id) do nothing;
